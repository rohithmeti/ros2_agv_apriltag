#!/usr/bin/env python3
"""Place AprilTag floor markers into the Gazebo world.

Input : config/apriltag_layout.yaml        (tag ids + x, y on the floor)
        models/apriltag_36h11_XXXXX/materials/textures/*.png  (tag images)
Output: models/apriltag_36h11_XXXXX/model.config + model.sdf  (one model per tag)
        worlds/indoor_world.sdf  -> the block between the APRILTAGS markers
                                    is replaced with one <include> per tag

Run from anywhere:  python3 scripts/place_apriltags.py
Then rebuild (colcon build) only if you are NOT using --symlink-install.
"""
import os
import re
import yaml

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "<!-- APRILTAGS BEGIN (generated by scripts/place_apriltags.py) -->"
END = "<!-- APRILTAGS END -->"

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <description>AprilTag {family} id {id}, floor marker, {size} m incl. white border</description>
</model>
"""

# Flat visual only, no collision: the robot drives over it and the lidar
# does not see it. Lifted 1.5 mm to avoid z-fighting with the ground plane.
# Visual is turned 180 deg (verified in Gazebo) so that layout yaw=0 means:
# tag top edge faces +y (north), right edge faces +x (east) = upright on the map.
MODEL_SDF = """<?xml version="1.0"?>
<sdf version="1.8">
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <visual name="tag">
        <pose>0 0 0.0015 0 0 3.14159265</pose>
        <cast_shadows>false</cast_shadows>
        <geometry>
          <plane><normal>0 0 1</normal><size>{size} {size}</size></plane>
        </geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
          <pbr>
            <metal>
              <albedo_map>model://{name}/materials/textures/{texture}</albedo_map>
              <roughness>1.0</roughness>
              <metalness>0.0</metalness>
            </metal>
          </pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
"""

INCLUDE = """    <include>
      <uri>model://{name}</uri>
      <name>apriltag_{id}</name>
      <pose>{x:.3f} {y:.3f} 0 0 0 {yaw:.4f}</pose>
    </include>"""


def main():
    with open(os.path.join(PKG, "config", "apriltag_layout.yaml")) as f:
        cfg = yaml.safe_load(f)
    size = cfg["texture_size"]
    family = cfg["family"]

    includes = []
    for t in cfg["tags"]:
        tid = int(t["id"])
        name = f"apriltag_36h11_{tid:05d}"
        texture = f"tag36_11_{tid:05d}.png"
        mdir = os.path.join(PKG, "models", name)
        if not os.path.isfile(os.path.join(mdir, "materials", "textures", texture)):
            raise SystemExit(f"missing texture for id {tid}: {mdir}/materials/textures/{texture}")
        with open(os.path.join(mdir, "model.config"), "w") as f:
            f.write(MODEL_CONFIG.format(name=name, family=family, id=tid, size=size))
        with open(os.path.join(mdir, "model.sdf"), "w") as f:
            f.write(MODEL_SDF.format(name=name, size=size, texture=texture))
        includes.append(INCLUDE.format(name=name, id=tid, x=t["x"], y=t["y"],
                                       yaw=float(t.get("yaw", 0.0))))

    world_path = os.path.join(PKG, cfg["world_file"])
    with open(world_path) as f:
        world = f.read()
    block = BEGIN + "\n" + "\n".join(includes) + "\n    " + END
    if BEGIN in world:
        world = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block,
                       world, flags=re.S)
    else:
        world = world.replace("  </world>", "    " + block + "\n\n  </world>")
    with open(world_path, "w") as f:
        f.write(world)
    print(f"placed {len(includes)} tags into {world_path}")


if __name__ == "__main__":
    main()
