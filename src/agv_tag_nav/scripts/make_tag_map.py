#!/usr/bin/env python3
"""apriltag_layout.yaml (sim: tag id + floor x,y,yaw) -> config/tag_map.yaml (the AGV's internal map).

Input : the sim layout file (argv[1])
Output: nodes (one per tag) + edges (lanes). Rules:
  * tags in the same lane column are joined to the next row (south->north), bidirectional
  * a connector tag (lane like 'WM') joins the two lane tags that share its y
After this, tag_map.yaml is the source of truth; edit directions/edges there (is_bidirectional).
"""
import sys, yaml

src, dst = sys.argv[1], sys.argv[2]
lay = yaml.safe_load(open(src))
tags = {t['id']: t for t in lay['tags']}
lanes = {}
for t in tags.values():
    if len(t['lane']) == 1:
        lanes.setdefault(t['lane'], []).append(t)
edges = []
for col in lanes.values():
    col.sort(key=lambda t: t['y'])
    edges += [(a['id'], b['id']) for a, b in zip(col, col[1:])]
for t in tags.values():
    if len(t['lane']) == 2:                       # connector: join the lane tags at the same y
        for ln in t['lane']:
            m = [u for u in lanes[ln] if abs(u['y'] - t['y']) < 0.05]
            edges.append((m[0]['id'], t['id']))
out = {
    'family': lay['family'], 'tag_size': lay['tag_size'], 'frame': 'map',
    'nodes': {i: {'x': t['x'], 'y': t['y'], 'yaw': t.get('yaw', 0.0), 'lane': t['lane']}
              for i, t in sorted(tags.items())},
    'edges': [{'from': a, 'to': b, 'is_bidirectional': True} for a, b in edges],
}
with open(dst, 'w') as f:
    f.write('# AGV internal map: node = AprilTag id, edge = lane. Generated by scripts/make_tag_map.py\n')
    yaml.safe_dump(out, f, sort_keys=False, default_flow_style=None)
print(f'{len(out["nodes"])} nodes, {len(edges)} edges -> {dst}')
